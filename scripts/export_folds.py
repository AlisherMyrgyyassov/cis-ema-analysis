"""Freeze the subject-disjoint folds into ``folds/cis_folds.json``.

The published results read that file (see ``src/data/cv.py``); this script only
exists so the file can be re-derived and audited. Run it once, diff the output,
and commit the result — do not regenerate it per experiment.

    python scripts/export_folds.py --out folds/cis_folds.json
"""
from __future__ import annotations

import argparse
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import pandas as pd  # noqa: E402

from src.config import DATA_DIR, N_FOLDS, N_VAL_SUBJECTS, FOLD_SEED  # noqa: E402
from src.data.cv import compute_folds  # noqa: E402


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--dataset", default=DATA_DIR, help="CIS-EMA corpus directory")
    ap.add_argument("--out", default=os.path.join("folds", "cis_folds.json"))
    ap.add_argument("--n-folds", type=int, default=N_FOLDS)
    ap.add_argument("--n-val", type=int, default=N_VAL_SUBJECTS)
    ap.add_argument("--seed", type=int, default=FOLD_SEED)
    args = ap.parse_args()

    manifest = pd.read_csv(os.path.join(args.dataset, "manifest.csv"))
    subjects = sorted(int(s) for s in manifest["subj"].unique())
    sex_map = (
        manifest.drop_duplicates("subj").set_index("subj")["sex"].astype(str).to_dict()
    )
    sex_map = {int(k): v for k, v in sex_map.items()}

    folds = compute_folds(
        subjects, sex_map, n_folds=args.n_folds, n_val=args.n_val, seed=args.seed
    )

    payload = {
        "description": (
            "Sex-stratified, subject-disjoint folds used for every reported result. "
            "Generated by scripts/export_folds.py; frozen so that library upgrades "
            "cannot reshuffle test speakers."
        ),
        "n_folds": args.n_folds,
        "n_val_subjects": args.n_val,
        "seed": args.seed,
        "n_subjects": len(subjects),
        "subjects": subjects,
        "sex_map": {str(k): v for k, v in sorted(sex_map.items())},
        "folds": folds,
    }
    os.makedirs(os.path.dirname(os.path.abspath(args.out)) or ".", exist_ok=True)
    with open(args.out, "w") as fh:
        json.dump(payload, fh, indent=2)
        fh.write("\n")

    print(f"wrote {args.out}")
    print(f"  {len(subjects)} subjects, {len(folds)} folds, seed {args.seed}")
    for i, f in enumerate(folds):
        print(
            f"  fold {i}: train {len(f['train']):2d}  val {len(f['val'])}  "
            f"test {len(f['test'])}  -> {f['test']}"
        )


if __name__ == "__main__":
    main()
